"""Package Lounge for a 2012 Samsung TV's User App Sync.

Writes widget/js/config.js, dist/Lounge_<ver>_Europe_<date>.zip and
dist/widgetlist.xml pointing at this Mac.

  python3 tools/build.py --host 192.168.1.20
"""
import argparse
import datetime
import json
import os
import re
import time
import zipfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
WIDGET = os.path.join(ROOT, "widget")
DIST = os.path.join(ROOT, "dist")
APP_ID = "Lounge"


def version():
    with open(os.path.join(WIDGET, "config.xml"), encoding="utf-8") as f:
        return re.search(r"<ver>([^<]+)</ver>", f.read()).group(1)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", required=True, help="this Mac's LAN IP, as the TV sees it")
    ap.add_argument("--server-port", type=int, default=80, help="port serve.py runs on for the TV")
    ap.add_argument("--tv-name", default=settings.TV.get("name") or "TV", help="shown in the Jarvis stats tree")
    ap.add_argument("--tv-model", default=settings.TV.get("model") or "")
    ap.add_argument("--user-name", default=settings.USER_NAME, help="what JARVIS calls you")
    args = ap.parse_args()

    server = f"http://{args.host}" + ("" if args.server_port == 80 else f":{args.server_port}")
    with open(os.path.join(WIDGET, "js", "config.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/build.py */\n")
        tz = time.localtime().tm_gmtoff
        cfg = {"server": server, "version": version(), "tzOffsetSec": tz,
               "tvName": args.tv_name, "tvModel": args.tv_model, "userName": args.user_name}
        f.write(f"var LOUNGE_CONFIG = {json.dumps(cfg)};\n")

    os.makedirs(DIST, exist_ok=True)
    for old in os.listdir(DIST):
        os.remove(os.path.join(DIST, old))

    name = f"{APP_ID}_{version()}_Europe_{datetime.date.today():%Y%m%d}.zip"
    path = os.path.join(DIST, name)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _, files in os.walk(WIDGET):
            for fn in sorted(files):
                if fn.startswith("."):
                    continue
                full = os.path.join(base, fn)
                z.write(full, os.path.relpath(full, WIDGET))

    size = os.path.getsize(path)
    with open(os.path.join(DIST, "widgetlist.xml"), "w", encoding="utf-8") as f:
        f.write(f"""<?xml version="1.0" encoding="UTF-8"?>
<rsp stat="ok">
<list>
<widget id="{APP_ID}">
<title>{APP_ID}</title>
<compression size="{size}" type="zip"/>
<description>A quiet home screen</description>
<download>{server}/Widget/{name}</download>
</widget>
</list>
</rsp>
""")
    print(f"built {name} ({size // 1024} KB); widgetlist points at {server}")


if __name__ == "__main__":
    main()
